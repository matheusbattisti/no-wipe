#!/usr/bin/env node
// no-wipe: one rules file (no-wipe.json) turned into the safety config of
// Claude Code, Codex, Cursor, Copilot CLI and Antigravity.

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HOOK = path.join(ROOT, "scripts", "no-wipe-hook.cjs");
const DEFAULT = path.join(ROOT, "no-wipe.default.json");
const [, , command = "help", ...rest] = process.argv;
const args = rest.filter((a) => !a.startsWith("--lang="));

const LANG_ARG = process.argv.find((a) => a.startsWith("--lang="))?.slice(7);
const PT = /^pt/i.test(LANG_ARG || Intl.DateTimeFormat().resolvedOptions().locale || "");
const t = (en, pt) => (PT ? pt : en);
const json = (o) => JSON.stringify(o, null, 2) + "\n";
const words = (c) => c.trim().split(/\s+/);

function write(project, rel, content) {
  const dest = path.join(project, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, content);
  console.log("  " + rel.replace(/\//g, path.sep));
}

function readRules(project) {
  const file = path.join(project, "no-wipe.json");
  if (!fs.existsSync(file)) {
    console.error(t(`Couldn't find ${file}. Run first: npx no-wipe init`, `Não achei ${file}. Rode primeiro: npx no-wipe init`));
    process.exit(1);
  }
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function generate(project) {
  const cfg = readRules(project);
  const { block = [], ask = [] } = cfg;
  const pt = /^pt/i.test(cfg.lang || (PT ? "pt" : ""));
  const blockMsg = cfg.message || (pt
    ? "Não apague arquivos em massa pelo terminal. Liste os caminhos exatos que quer apagar e peça para o usuário."
    : "Do not bulk-delete files from the terminal. List the exact paths you want to delete and ask the user.");
  const askMsg = pt ? "Este comando precisa da aprovação do usuário antes de rodar." : "This command needs the user's approval before it runs.";

  console.log("\n" + t(`Generating each tool's config in ${project}`, `Gerando a configuração de cada IA em ${project}`) + "\n");

  // Claude Code
  const cc = (l) => l.flatMap((c) => [`Bash(${c} *)`, `PowerShell(${c} *)`]);
  write(project, ".claude/settings.json", json({
    env: { CLAUDE_CODE_USE_POWERSHELL_TOOL: "1" },
    permissions: { disableBypassPermissionsMode: "disable", deny: cc(block), ask: cc(ask) },
    hooks: { PreToolUse: [{ matcher: "Bash|PowerShell", hooks: [{
      type: "command", command: "node",
      args: ["${CLAUDE_PROJECT_DIR}/.claude/hooks/no-wipe-hook.cjs"],
      timeout: 10, onFailure: "block",
    }] }] },
  }));
  write(project, ".claude/hooks/no-wipe-hook.cjs", fs.readFileSync(HOOK, "utf8"));

  // Codex
  write(project, ".codex/config.toml", [
    "# Generated by no-wipe from no-wipe.json",
    'sandbox_mode = "workspace-write"', 'approval_policy = "on-request"', "",
    "[sandbox_workspace_write]", "network_access = false", "",
    "[windows]", 'sandbox = "elevated"', "",
  ].join("\n"));
  const rule = (c, decision) => {
    const w = words(c);
    const variants = [w];
    if (/[A-Z]/.test(c)) variants.push(w.map((x) => x.toLowerCase()));
    if (w.length === 1 && ["rd", "rmdir", "del", "erase"].includes(w[0])) variants.push(["cmd", "/c", w[0]]);
    const why = decision === "prompt" ? askMsg : blockMsg;
    return variants.map((p) => `prefix_rule(\n    pattern = ${JSON.stringify(p)},\n    decision = "${decision}",\n    justification = ${JSON.stringify(why)},\n)\n`).join("\n");
  };
  write(project, ".codex/rules/default.rules", [
    "# Generated by no-wipe from no-wipe.json",
    ...block.map((c) => rule(c, "forbidden")),
    ...ask.map((c) => rule(c, "prompt")),
  ].join("\n"));

  // Cursor (CLI): anything not on the allow list already asks for approval
  write(project, ".cursor/cli.json", json({ permissions: {
    allow: ["Shell(ls)", "Shell(dir)", "Shell(git status)", "Shell(git diff)", "Shell(npm run)"],
    deny: [...block.map((c) => `Shell(${c})`), "Write(../**)"],
  } }));

  // Copilot CLI
  write(project, "copilot-guarded.ps1", [
    "# Generated by no-wipe. Starts Copilot CLI in its sandbox with the blocked commands denied.",
    `copilot --sandbox ${block.map((c) => `--deny-tool='shell(${c})'`).join(" ")} @args`, "",
  ].join("\n"));

  // Antigravity (CLI): copy to ~/.gemini/antigravity-cli/settings.json
  write(project, "antigravity-cli-settings.json", json({
    enableTerminalSandbox: true,
    permissions: { allow: [], deny: block.map((c) => `command(${c})`), ask: ask.map((c) => `command(${c})`) },
  }));

  console.log("\n" + t(
    `Done: ${block.length} blocked commands and ${ask.length} that ask for approval, across 5 tools.\nTo change a rule, edit no-wipe.json and run: npx no-wipe generate`,
    `Pronto: ${block.length} comandos bloqueados e ${ask.length} que pedem aprovação, em 5 ferramentas.\nPara mudar uma regra, edite o no-wipe.json e rode: npx no-wipe generate`
  ) + "\n");
}

function check(text) {
  const r = spawnSync(process.execPath, [HOOK, "--project", process.cwd(), "--no-log"], {
    input: JSON.stringify({ tool_name: "Bash", tool_input: { command: text } }),
    encoding: "utf8",
  });
  let pt = PT;
  try { pt = /^pt/i.test(JSON.parse(fs.readFileSync(path.join(process.cwd(), "no-wipe.json"), "utf8")).lang || (PT ? "pt" : "")); } catch { /* no config here */ }
  const tt = (en, p) => (pt ? p : en);
  if (r.status === 2) {
    console.log("\x1b[31m" + tt("BLOCKED", "BLOQUEADO") + "\x1b[0m  " + text);
    console.log("  " + r.stderr.trim().replace(/\n/g, "\n  "));
  } else {
    console.log("\x1b[32m" + tt("ALLOWED", "LIBERADO") + "\x1b[0m   " + text);
  }
}

switch (command) {
  case "init": {
    const project = path.resolve(args[0] || ".");
    const file = path.join(project, "no-wipe.json");
    if (!fs.existsSync(file)) {
      fs.mkdirSync(project, { recursive: true });
      const rules = JSON.parse(fs.readFileSync(DEFAULT, "utf8"));
      fs.writeFileSync(file, json({ lang: PT ? "pt" : "en", ...rules }));
      console.log("\n" + t(`Created ${file} with the default rules.`, `Criei ${file} com as regras padrão.`));
    }
    generate(project);
    break;
  }
  case "generate":
    generate(path.resolve(args[0] || "."));
    break;
  case "check":
    if (!args.length) { console.error('Usage: npx no-wipe check "command"'); process.exit(1); }
    check(args.join(" "));
    break;
  case "test": {
    const r = spawnSync(process.execPath, [path.join(ROOT, "test", "run-tests.mjs"), ...args], { stdio: "inherit" });
    process.exit(r.status ?? 1);
  }
  default:
    console.log(t(`
no-wipe: stop AI coding agents from wiping your files (Claude Code, Codex, Cursor, Copilot, Antigravity)

  npx no-wipe init [folder]      create no-wipe.json and generate each tool's config
  npx no-wipe generate [folder]  regenerate after editing no-wipe.json
  npx no-wipe check "command"    show whether a command would be blocked (runs nothing)
  npx no-wipe test               run the hook tests
`, `
no-wipe: impede agentes de IA de apagar seus arquivos (Claude Code, Codex, Cursor, Copilot, Antigravity)

  npx no-wipe init [pasta]       cria o no-wipe.json e gera a configuração de cada IA
  npx no-wipe generate [pasta]   gera de novo depois de editar o no-wipe.json
  npx no-wipe check "comando"    mostra se o comando seria bloqueado (não executa nada)
  npx no-wipe test               roda os testes do hook
`));
}
